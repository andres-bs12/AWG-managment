import { test, expect } from '@playwright/test'
import { open, choose, next, mobile, photo, review, axe } from './helpers'

for (const locale of ['de', 'en']) test(`only the second ornament has a back name (${locale})`, async ({ page }) => {
  await open(page, locale)
  const list = page.getByRole('list', { name: locale === 'de' ? 'In deiner Bestellung' : 'In your order' })
  const rows = list.locator(':scope > li')
  const no = page.getByRole('radio', { name: /^(Nein|No)$/ })
  const yes = page.getByRole('radio', { name: /^(Ja|Yes),/ })
  await choose(page)
  if (mobile(page)) await next(page).click()
  await expect(no).toBeChecked()
  if (mobile(page)) await next(page).click()
  await page.locator('input[id^="pet-"]').fill('Luna')
  await page.locator('input[type=file]').setInputFiles(photo)
  await expect(page.getByRole('img', { name: /^(Foto|Photo) 1 (von|of) Luna$/ })).toBeVisible()
  await page.locator('#buy-add').click()
  await expect(page.locator('#ornament-editor-heading')).toBeFocused()
  await expect(page.locator('#ornament-editor-heading')).toBeInViewport({ ratio: 1 })
  await expect(page.locator('#ornament-editor-heading')).toContainText(locale === 'de' ? 'Kugel 2 von 2' : 'Ornament 2 of 2')
  await choose(page)
  if (mobile(page)) await next(page).click()
  await yes.check()
  // Empty-name validation belongs only to ornament 2 and clears when No is chosen.
  await next(page).click()
  await expect(page.locator('input[id^="back-"]')).toHaveAttribute('aria-invalid', 'true')
  await no.check()
  await expect(page.locator('[id^="back-"][id$="-error"]')).toHaveCount(0)
  await yes.check()
  await expect(page.locator('input[id^="back-"]')).not.toHaveAttribute('aria-invalid', 'true')
  await page.locator('input[id^="back-"]').fill('MAX')
  if (mobile(page)) await next(page).click()
  await page.locator('input[id^="pet-"]').fill('Max')
  await page.locator('input[type=file]').setInputFiles(photo)
  await expect(page.getByRole('img', { name: /^(Foto|Photo) 1 (von|of) Max$/ })).toBeVisible()
  await expect(rows).toHaveCount(2)
  await expect(rows.nth(0)).toContainText(locale === 'de' ? 'Ohne Namen' : 'No name')
  await expect(rows.nth(1)).toContainText('Name: MAX')
  await expect(rows.nth(1)).toContainText(locale === 'de' ? 'In Bearbeitung' : 'Editing')
  await rows.nth(0).getByRole('button', { name: /bearbeiten|Edit/ }).click()
  if (mobile(page)) await next(page).click()
  await expect(no).toBeChecked()
  await expect(page.locator('input[id^="back-"]')).toHaveCount(0)
  await rows.nth(1).getByRole('button', { name: /bearbeiten|Edit/ }).click()
  if (mobile(page)) { await next(page).click(); await next(page).click() }
  await review(page)
  const first = page.getByRole('region', { name: /^(Kugel|Ornament) 1/ })
  const second = page.getByRole('region', { name: /^(Kugel|Ornament) 2/ })
  await expect(first).toContainText(locale === 'de' ? 'Ohne Namen' : 'No name')
  await expect(first).not.toContainText('+€')
  await expect(second).toContainText('MAX')
  await expect(second).toContainText(/12[,.]99/)
  await expect(first).toContainText(/49[,.]99/)
  await expect(second).toContainText(/62[,.]98/)
  await axe(page)
  await page.evaluate(async () => {
    const path = '/src/api/client.ts'; const { api } = await import(path)
    api.shop.checkout = async (input: unknown) => { (window as unknown as { checkout: unknown }).checkout = input; return new Promise<never>(() => {}) }
  })
  await page.locator('#buy-terms').check()
  await page.locator('form button[type=submit]').click()
  await expect.poll(() => page.evaluate(() => (window as unknown as { checkout?: unknown }).checkout)).toMatchObject({
    items: [{ petName: 'Luna', withName: false }, { petName: 'Max', withName: true, backName: 'MAX' }],
  })
})

test('overview supports keyboard edit, removal, max count and narrow reflow', async ({ page }) => {
  await open(page, 'en')
  const rows = page.getByRole('list', { name: 'In your order' }).locator(':scope > li')
  const max = await page.evaluate(async () => { const path = '/src/api/client.ts'; const { api } = await import(path); return (await api.shop.getConfig()).maxItems })
  for (let count = 1; count < max; count++) {
    await page.locator('#buy-add').click()
    await expect(page.locator('#ornament-editor-heading')).toBeFocused()
  }
  await expect(rows).toHaveCount(max)
  await expect(page.locator('#buy-add')).toBeDisabled()
  await expect(page.getByRole('status').filter({ hasText: /maximum|up to|limit/i })).toBeVisible()
  const edit = rows.nth(0).getByRole('button', { name: /Edit/ })
  await edit.focus(); await page.keyboard.press('Enter')
  await expect(page.locator('#ornament-editor-heading')).toBeFocused()
  await rows.nth(0).getByRole('button', { name: /Remove/ }).click()
  await expect(rows).toHaveCount(max - 1)
  await expect(page.locator('#ornament-editor-heading')).toBeFocused()
  await expect(page.locator('#buy-add')).toBeEnabled()
  await page.setViewportSize({ width: 360, height: 740 })
  expect(await page.evaluate(() => document.scrollingElement!.scrollWidth <= document.scrollingElement!.clientWidth && document.body.scrollWidth <= innerWidth)).toBe(true)
  for (const button of await rows.nth(0).getByRole('button').all()) expect((await button.boundingBox())!.height).toBeGreaterThanOrEqual(56)
  await axe(page)
  await page.setViewportSize({ width: 1920, height: 1080 })
  expect(await page.evaluate(() => document.scrollingElement!.scrollWidth <= document.scrollingElement!.clientWidth && document.body.scrollWidth <= innerWidth)).toBe(true)
})

test('a named first ornament never turns on the name for a new ornament', async ({ page }) => {
  await open(page, 'en'); await choose(page)
  if (mobile(page)) await next(page).click()
  await page.getByRole('radio', { name: /^Yes,/ }).check()
  await page.locator('input[id^="back-"]').fill('LUNA')
  await page.locator('#buy-add').click()
  await choose(page)
  if (mobile(page)) await next(page).click()
  await expect(page.getByRole('radio', { name: 'No', exact: true })).toBeChecked()
  await expect(page.locator('input[id^="back-"]')).toHaveCount(0)
  const rows = page.getByRole('list', { name: 'In your order' }).locator(':scope > li')
  await expect(rows.nth(0)).toContainText('Name: LUNA')
  await expect(rows.nth(1)).toContainText('No name')
  await rows.nth(0).getByRole('button', { name: 'Edit Ornament 1', exact: true }).click()
  if (mobile(page)) await next(page).click()
  await expect(page.getByRole('radio', { name: /^Yes,/ })).toBeChecked()
  await expect(page.locator('input[id^="back-"]')).toHaveValue('LUNA')
})
