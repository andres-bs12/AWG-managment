package com.artwithgab.awg_tracking.model;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.time.Instant;
import java.util.UUID;

/** Reference photo uploaded through the customer form. The bytes live on disk (see PhotoStorageService). */
@Entity
@Getter
@Setter
@NoArgsConstructor
public class StoredPhoto {
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    @Column(nullable = false)
    private String originalName;

    @Column(nullable = false)
    private String contentType;

    private long sizeBytes;

    /** File name inside the upload directory. Generated by the server, never from user input. */
    @Column(nullable = false, unique = true)
    private String storageKey;

    @Column(nullable = false)
    private UUID orderItemId;

    @Column(nullable = false)
    private Instant createdAt;
}
